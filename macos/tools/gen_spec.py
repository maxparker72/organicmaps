#!/usr/bin/env python3
"""Render macos/docs/SPEC.md from macos/docs/features.json.

features.json is the source of truth for feature IDs, priorities, built status,
behaviour and acceptance checks. Edit it, then run:

    python3 macos/tools/gen_spec.py
"""

import json
from collections import Counter
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent / "docs"
BUILT = {"done": "Built", "partial": "Partial", "missing": "Missing", "planned": "Planned", "dropped": "Dropped"}


def cell(text):
  return (text or "").replace("|", "\\|").replace("\n", " ")


def main():
  spec = json.loads((DOCS / "features.json").read_text())
  features = spec["features"]
  counts = Counter(f["status"] for f in features)

  lines = [
      "# mapo: feature spec",
      "",
      "<!-- Generated by macos/tools/gen_spec.py from features.json. Edit features.json, not this file. -->",
      "",
      "This is the source of truth for what the app does. Every feature has a stable ID.",
      "Tasks, commits and tests refer to these IDs, for example `[macos] LIB-06: Keep imported track widths`.",
      "",
      "**Rules**",
      "",
      "- **Built** means the code exists and is reachable from the UI. A feature is **done** only when its",
      "  acceptance check also passes on a Release build. Test results are recorded in the project tracker.",
      "- Change behaviour here first, then in code. A commit that changes behaviour updates `features.json`.",
      "- New features get the next free ID in their group. IDs are never reused.",
      "- Dropped features stay listed with the decision that dropped them (DECISIONS.md).",
      "- **P0** needed for the first tester build, **P1** for beta, **P2** nice to have, **P3** later or never.",
      "- `R-B`, `R-S` and `R-E` references point to findings in REVIEW-2026-10.md.",
      "",
      f"Status on {spec['updated']}: " + ", ".join(f"{counts.get(k, 0)} {v.lower()}" for k, v in BUILT.items()) + ".",
      "",
  ]
  for prefix, title in spec["categories"].items():
    rows = [f for f in features if f["fid"].split("-")[0] == prefix]
    if not rows:
      continue
    lines += [f"## {title} ({prefix})", "",
              "| ID | Feature | Pri | Built | Behaviour | Acceptance check | Known gaps |",
              "|---|---|---|---|---|---|---|"]
    for f in rows:
      lines.append(f"| {f['fid']} | {cell(f['name'])} | {f['priority']} | {BUILT[f['status']]} | "
                   f"{cell(f['scope'])} | {cell(f['accept'])} | {cell(f['notes'])} |")
    lines.append("")
  (DOCS / "SPEC.md").write_text("\n".join(lines))
  print(f"Wrote SPEC.md: {len(features)} features, {dict(counts)}")


if __name__ == "__main__":
  main()
